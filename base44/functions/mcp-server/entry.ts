Deno.serve(async (req) => {
  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) return mcpError('UNAUTHORIZED', 'Authentication required', 401);

    const isAdmin = user.role === 'admin';

    let body;
    try {
      body = await readBody(req);
    } catch (e) {
      return mcpError(e.code || 'BAD_REQUEST', e.message || 'Invalid request body', e.code === 'PAYLOAD_TOO_LARGE' ? 413 : 400);
    }

    const { method, params = {} } = body;

    // ---- resources/list ----
    if (method === 'resources/list') {
      return Response.json({ resources: buildEntityResources() });
    }

    // ---- resources/read ----
    if (method === 'resources/read') {
      const { uri } = params;
      if (!uri || typeof uri !== 'string') return mcpError('INVALID_PARAMS', 'uri is required');
      const match = uri.match(/^([a-z]+):\/\/list$/);
      if (!match) return mcpError('UNKNOWN_RESOURCE', `Unknown resource URI: ${uri}`, 404);
      const entityName = ENTITY_ALLOWLIST.find(n => n.toLowerCase() === match[1]);
      if (!entityName) return mcpError('UNKNOWN_RESOURCE', `Unknown resource URI: ${uri}`, 404);
      const contents = await base44.entities[entityName].list();
      return Response.json({ contents });
    }

    // ---- tools/list ----
    if (method === 'tools/list') {
      return Response.json({
        tools: [
          ...CORE_TOOLS,
          ...buildEntityTools(),
          ...CLOUDFLARE_TOOLS,
          ...LLM_TOOLS
        ]
      });
    }

    // ---- tools/call ----
    if (method === 'tools/call') {
      const { name, arguments: args = {} } = params;
      if (!name || typeof name !== 'string') return mcpError('INVALID_PARAMS', 'tool name is required');

      // Core: entities_list
      if (name === 'entities_list') {
        return Response.json({ result: ENTITY_ALLOWLIST });
      }

      // Core: functions_list
      if (name === 'functions_list') {
        return Response.json({ result: FUNCTION_ALLOWLIST });
      }

      // Core: invoke_function (admin only)
      if (name === 'invoke_function') {
        if (!isAdmin) return mcpError('FORBIDDEN', 'Admin role required to invoke backend functions', 403);
        const fnName = args.function_name;
        if (!FUNCTION_ALLOWLIST.includes(fnName)) {
          return mcpError('FUNCTION_NOT_ALLOWED', `Function "${fnName}" is not in the MCP allowlist`);
        }
        const result = await base44.asServiceRole.functions.invoke(fnName, args.params || {});
        return Response.json({ result: result?.data ?? result });
      }

      // LLM: models_list
      if (name === 'llm_models_list') {
        return Response.json({ result: LLM_MODELS });
      }

      // LLM: invoke
      if (name === 'llm_invoke') {
        const prompt = args.prompt;
        if (!prompt || typeof prompt !== 'string') return mcpError('INVALID_PARAMS', 'prompt is required');
        const model = args.model || 'automatic';
        const modelDef = LLM_MODELS.find(m => m.id === model);
        if (!modelDef) return mcpError('UNKNOWN_MODEL', `Unknown model: ${model}`);
        const useWeb = !!args.add_context_from_internet;
        if (useWeb && !modelDef.web_search) {
          return mcpError('MODEL_CAPABILITY', `Model "${model}" does not support web search. Use a web_search-capable model.`);
        }
        const llmArgs = { prompt };
        if (model !== 'automatic') llmArgs.model = model;
        if (useWeb) llmArgs.add_context_from_internet = true;
        if (args.response_json_schema && typeof args.response_json_schema === 'object') {
          if (args.response_json_schema.type !== 'object') {
            return mcpError('INVALID_PARAMS', 'response_json_schema root must be type "object"');
          }
          llmArgs.response_json_schema = args.response_json_schema;
        }
        if (Array.isArray(args.file_urls) && args.file_urls.length) {
          llmArgs.file_urls = args.file_urls;
        }
        const result = await base44.asServiceRole.integrations.Core.InvokeLLM(llmArgs);
        return Response.json({ result });
      }

      // Cloudflare tools (admin only; credentials supplied per call)
      if (name.startsWith('cf_')) {
        if (!isAdmin) return mcpError('FORBIDDEN', 'Admin role required for Cloudflare tools', 403);
        const token = args.api_token;
        const accountId = args.account_id;

        if (name === 'cf_zones_list') {
          return Response.json(await cfGet('/zones', token));
        }
        if (name === 'cf_dns_records_list') {
          if (!args.zone_id) return mcpError('INVALID_PARAMS', 'zone_id is required');
          return Response.json(await cfGet(`/zones/${args.zone_id}/dns_records`, token));
        }
        if (name === 'cf_workers_list') {
          return Response.json(await cfGet(`/accounts/${accountId}/workers/scripts`, token));
        }
        if (name === 'cf_kv_namespaces_list') {
          return Response.json(await cfGet(`/accounts/${accountId}/storage/kv/namespaces`, token));
        }
        if (name === 'cf_r2_buckets_list') {
          return Response.json(await cfGet(`/accounts/${accountId}/r2/buckets`, token));
        }
        return mcpError('UNKNOWN_TOOL', `Unknown Cloudflare tool: ${name}`);
      }

      // Generic entity CRUD (adaptable — routes by entity name prefix)
      const entityMatch = ENTITY_ALLOWLIST.find(en => name.startsWith(`${en.toLowerCase()}_`));
      if (entityMatch) {
        const op = name.slice(entityMatch.length + 1);
        const entity = base44.entities[entityMatch];
        if (op === 'list') {
          const limit = Math.min(args.limit || 50, 200);
          const sort = args.sort || '-created_date';
          let result;
          if (args.filter && typeof args.filter === 'object') {
            result = await entity.filter(args.filter, sort, limit);
          } else {
            result = await entity.list(sort, limit);
          }
          return Response.json({ result });
        }
        if (op === 'get') {
          if (!args.id) return mcpError('INVALID_PARAMS', 'id is required');
          const result = await entity.get(args.id);
          return Response.json({ result });
        }
        if (op === 'create') {
          if (!args.data || typeof args.data !== 'object') return mcpError('INVALID_PARAMS', 'data object is required');
          const result = await entity.create(args.data);
          return Response.json({ result });
        }
        if (op === 'update') {
          if (!args.id) return mcpError('INVALID_PARAMS', 'id is required');
          if (!args.data || typeof args.data !== 'object') return mcpError('INVALID_PARAMS', 'data object is required');
          const result = await entity.update(args.id, args.data);
          return Response.json({ result });
        }
        if (op === 'delete') {
          if (!args.id) return mcpError('INVALID_PARAMS', 'id is required');
          const result = await entity.delete(args.id);
          return Response.json({ result });
        }
      }

      return mcpError('UNKNOWN_TOOL', `Unknown tool: ${name}`, 404);
    }

    // ---- ping (health check) ----
    if (method === 'ping') {
      return Response.json({ result: { status: 'ok', user: user.email, admin: isAdmin } });
    }

    return mcpError('UNKNOWN_METHOD', `Unknown MCP method: ${method}`, 400);
  } catch (error) {
    // Sanitized error — never leak internals to external callers
    const message = error?.message || 'Internal server error';
    return mcpError('INTERNAL_ERROR', message, 500);
  }
});