/** Max payload size for MCP requests (1MB) to prevent abuse. */
const MAX_BODY_BYTES = 1024 * 1024;
/** Timeout for external (Cloudflare) API calls. */
const CF_TIMEOUT_MS = 15000;

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/** Structured error response with a stable code. */
function mcpError(code, message, status = 400) {
  return Response.json({ error: { code, message } }, { status });
}

/** Read and size-limit the request body. */
async function readBody(req) {
  const text = await req.text();
  if (text.length > MAX_BODY_BYTES) {
    throw { code: 'PAYLOAD_TOO_LARGE', message: 'Request body exceeds 1MB limit' };
  }
  return text ? JSON.parse(text) : {};
}

/** Fetch with timeout via AbortController for resilience against hanging calls. */
async function fetchWithTimeout(url, options = {}, timeoutMs = CF_TIMEOUT_MS) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const res = await fetch(url, { ...options, signal: controller.signal });
    return res;
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Generic Cloudflare GET with auth + standardized error handling.
 * Credentials are supplied per-call by an admin (api_token, account_id) —
 * no platform secrets required, keeping the MCP server runnable without config.
 */
async function cfGet(path, apiToken, accountId) {
  if (!apiToken) {
    return { error: { code: 'CF_NOT_CONFIGURED', message: 'Cloudflare api_token is required in the tool arguments.' } };
  }
  const url = path.startsWith('http') ? path : `https://api.cloudflare.com/client/v4${path}`;
  try {
    const res = await fetchWithTimeout(url, {
      headers: { 'Authorization': `Bearer ${apiToken}`, 'Content-Type': 'application/json' }
    });
    const data = await res.json();
    if (!res.ok) {
      return { error: { code: `CF_HTTP_${res.status}`, message: data?.errors?.[0]?.message || `Cloudflare API error ${res.status}` } };
    }
    return { result: data.result };
  } catch (err) {
    if (err.name === 'AbortError') {
      return { error: { code: 'CF_TIMEOUT', message: 'Cloudflare API request timed out' } };
    }
    return { error: { code: 'CF_REQUEST_FAILED', message: err.message || 'Cloudflare request failed' } };
  }
}

