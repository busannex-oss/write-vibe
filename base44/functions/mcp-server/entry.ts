function buildEntityTools() {
  const tools = [];
  for (const name of ENTITY_ALLOWLIST) {
    tools.push({
      name: `${name.toLowerCase()}_list`,
      description: `List ${name} records (user-scoped).`,
      inputSchema: {
        type: 'object',
        properties: {
          sort: { type: 'string', description: 'Sort field (e.g. -created_date)' },
          limit: { type: 'number', description: 'Max results (default 50, max 200)' },
          filter: { type: 'object', description: 'Query filter object' }
        }
      }
    });
    tools.push({
      name: `${name.toLowerCase()}_get`,
      description: `Get a single ${name} by ID.`,
      inputSchema: { type: 'object', properties: { id: { type: 'string' } }, required: ['id'] }
    });
    tools.push({
      name: `${name.toLowerCase()}_create`,
      description: `Create a new ${name} record.`,
      inputSchema: { type: 'object', properties: { data: { type: 'object' } }, required: ['data'] }
    });
    tools.push({
      name: `${name.toLowerCase()}_update`,
      description: `Update a ${name} record by ID.`,
      inputSchema: {
        type: 'object',
        properties: { id: { type: 'string' }, data: { type: 'object' } },
        required: ['id', 'data']
      }
    });
    tools.push({
      name: `${name.toLowerCase()}_delete`,
      description: `Delete a ${name} record by ID.`,
      inputSchema: { type: 'object', properties: { id: { type: 'string' } }, required: ['id'] }
    });
  }
  return tools;
}

function buildEntityResources() {
  return ENTITY_ALLOWLIST.map(name => ({
    uri: `${name.toLowerCase()}://list`,
    name: name,
    description: `List all ${name} records for the current user`,
    mimeType: 'application/json'
  }));
}

