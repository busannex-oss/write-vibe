import { format, subDays, startOfDay, addHours } from "date-fns";

const dayKey = (d) => format(startOfDay(new Date(d)), "yyyy-MM-dd");

/** Visits per day for the last 30 days. */
export function buildViewTrend(views) {
  const counts = {};
  views.forEach((v) => {
    const key = dayKey(v.viewed_at || v.created_date);
    counts[key] = (counts[key] || 0) + 1;
  });
  return Array.from({ length: 30 }, (_, i) => {
    const date = subDays(new Date(), 29 - i);
    const key = format(date, "yyyy-MM-dd");
    return { label: format(date, "MMM d"), views: counts[key] || 0 };
  });
}

/** Visit counts grouped by traffic source. */
export function buildSourceBreakdown(views) {
  return views.reduce((acc, v) => {
    const s = v.source || "direct";
    acc[s] = (acc[s] || 0) + 1;
    return acc;
  }, {});
}

/**
 * Attention generated by each published marketing post — visits and newsletter
 * signups recorded in the 72 hours after it went out.
 */
export function buildMilestoneAttention(posts, views, subscribers) {
  return posts
    .filter((p) => p.posted_at)
    .map((p) => {
      const start = new Date(p.posted_at);
      const end = addHours(start, 72);
      const inWindow = (ts) => {
        if (!ts) return false;
        const t = new Date(ts);
        return t >= start && t <= end;
      };
      const scopedViews = views.filter(
        (v) => inWindow(v.viewed_at || v.created_date) && (!p.book_id || v.book_id === p.book_id)
      );
      const scopedSubs = subscribers.filter(
        (s) => inWindow(s.subscribed_at || s.created_date) && (!p.book_id || s.book_id === p.book_id)
      );
      return {
        id: p.id,
        caption: p.caption,
        platforms: p.platforms || [],
        dateLabel: format(start, "MMM d, yyyy"),
        views: scopedViews.length,
        subscribers: scopedSubs.length
      };
    })
    .sort((a, b) => b.views + b.subscribers * 3 - (a.views + a.subscribers * 3));
}

/**
 * Daily visits over the last `days` days, annotated with marketing milestones
 * that happened that day and flagged when the day is a traffic spike
 * (more than 1.75x the period average).
 */
export function buildMilestoneTrafficSeries(views, books = [], posts = [], days = 60) {
  const viewCounts = {};
  views.forEach((v) => {
    const key = dayKey(v.viewed_at || v.created_date);
    viewCounts[key] = (viewCounts[key] || 0) + 1;
  });

  const milestones = {};
  const addMilestone = (date, label, kind) => {
    if (!date) return;
    const key = dayKey(date);
    (milestones[key] = milestones[key] || []).push({ label, kind });
  };
  books.forEach((b) => {
    addMilestone(b.website_config?.release_date, `${b.title} launch`, "release");
    addMilestone(b.amazon_kdp_submitted_at, `${b.title} — KDP submitted`, "kdp");
    addMilestone(b.amazon_acx_submitted_at, `${b.title} — audiobook submitted`, "acx");
  });
  posts
    .filter((p) => p.posted_at)
    .forEach((p) => addMilestone(p.posted_at, (p.caption || "Social post").slice(0, 60), "social"));

  const series = Array.from({ length: days }, (_, i) => {
    const date = subDays(new Date(), days - 1 - i);
    const key = format(date, "yyyy-MM-dd");
    return {
      label: format(date, "MMM d"),
      key,
      views: viewCounts[key] || 0,
      milestones: milestones[key] || []
    };
  });

  const total = series.reduce((s, d) => s + d.views, 0);
  const avg = total / days;
  return series.map((d) => ({
    ...d,
    spike: avg > 0 && d.views > avg * 1.75,
    milestoneCount: d.milestones.length
  }));
}

/** Per-book draft engagement summary. */
export function buildBookEngagement(books, comments, reviews, views) {
  return books
    .map((b) => {
      const bookComments = comments.filter((c) => c.book_id === b.id);
      const bookReviews = reviews.filter((r) => r.book_id === b.id);
      const chaptersWithFeedback = new Set(
        bookComments.filter((c) => c.chapter_number != null).map((c) => c.chapter_number)
      ).size;
      return {
        id: b.id,
        title: b.title,
        chapterCount: (b.manuscript_chapters || b.table_of_contents || []).length,
        chaptersWithFeedback,
        commentCount: bookComments.length,
        openComments: bookComments.filter((c) => c.status === "open").length,
        avgRating: bookReviews.length
          ? bookReviews.reduce((s, r) => s + (r.rating || 0), 0) / bookReviews.length
          : null,
        views: views.filter((v) => v.book_id === b.id).length
      };
    })
    .sort((a, b) => b.views + b.commentCount - (a.views + a.commentCount));
}